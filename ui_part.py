import customtkinter as ctk

def build_interface(app):
    app.grid_columnconfigure(0, weight=3)
    app.grid_columnconfigure(1, weight=2)
    app.grid_rowconfigure(1, weight=1)
    top = ctk.CTkFrame(app, height=55)
    top.grid(row=0, column=0, columnspan=2, sticky="ew", padx=12, pady=(12, 6))
    ctk.CTkButton(top, text="📁 Выбрать папку с фото", font=("Arial", 13, "bold"), fg_color="#2563eb", command=app.select_folder).pack(side="left", padx=10, pady=10)
    app.folder_lbl = ctk.CTkLabel(top, text="Папка не выбрана", text_color="#9ca3af")
    app.folder_lbl.pack(side="left", padx=10)
    app.count_lbl = ctk.CTkLabel(top, text="Кадров: 0", font=("Arial", 13, "bold"), text_color="#38bdf8")
    app.count_lbl.pack(side="right", padx=15)
    left = ctk.CTkFrame(app)
    left.grid(row=1, column=0, sticky="nsew", padx=(12, 6), pady=6)
    left.grid_rowconfigure(0, weight=1)
    left.grid_columnconfigure(0, weight=1)
    app.preview_box = ctk.CTkLabel(left, text="Выберите папку с фотографиями,\nчтобы увидеть предпросмотр", fg_color="#111827", corner_radius=8, font=("Arial", 14), text_color="#6b7280")
    app.preview_box.grid(row=0, column=0, sticky="nsew", padx=12, pady=(12, 6))
    ctrl = ctk.CTkFrame(left, fg_color="transparent")
    ctrl.grid(row=1, column=0, sticky="ew", padx=12, pady=(0, 12))
    app.btn_play = ctk.CTkButton(ctrl, text="▶ Предпросмотр", width=130, fg_color="#059669", command=app.toggle_play)
    app.btn_play.pack(side="left", padx=(0, 10))
    app.frame_slider = ctk.CTkSlider(ctrl, from_=0, to=1, command=app.on_slider_move)
    app.frame_slider.set(0)
    app.frame_slider.pack(side="left", fill="x", expand=True, padx=5)
    app.frame_info = ctk.CTkLabel(ctrl, text="0 / 0", width=80)
    app.frame_info.pack(side="right", padx=(5, 0))
    right = ctk.CTkFrame(app)
    right.grid(row=1, column=1, sticky="nsew", padx=(6, 12), pady=6)
    ctk.CTkLabel(right, text="Настройки таймлапса", font=("Arial", 16, "bold")).pack(pady=(15, 10))
    row1 = ctk.CTkFrame(right, fg_color="transparent")
    row1.pack(fill="x", padx=15, pady=8)
    fps_box = ctk.CTkFrame(row1, fg_color="transparent")
    fps_box.pack(side="left", fill="x", expand=True, padx=(0, 5))
    ctk.CTkLabel(fps_box, text="Частота (FPS):", anchor="w").pack(fill="x")
    app.fps_entry = ctk.CTkEntry(fps_box)
    app.fps_entry.insert(0, "30")
    app.fps_entry.pack(fill="x", pady=(4, 0))
    res_box = ctk.CTkFrame(row1, fg_color="transparent")
    res_box.pack(side="left", fill="x", expand=True, padx=(5, 0))
    ctk.CTkLabel(res_box, text="Разрешение:", anchor="w").pack(fill="x")
    app.res_menu = ctk.CTkOptionMenu(res_box, values=["Нативное", "2K (2560x1440)", "1080p (Full HD)", "720p (HD)", "480p (SD)"])
    app.res_menu.set("1080p (Full HD)")
    app.res_menu.pack(fill="x", pady=(4, 0))
    i_box = ctk.CTkFrame(right)
    i_box.pack(fill="x", padx=15, pady=10)
    i_hdr = ctk.CTkFrame(i_box, fg_color="transparent")
    i_hdr.pack(fill="x", padx=10, pady=(8, 0))
    app.interp_sw = ctk.CTkSwitch(i_hdr, text="Интерполяция кадров", font=("Arial", 13, "bold"), command=app.toggle_ui)
    app.interp_sw.pack(side="left")
    app.interp_lbl = ctk.CTkLabel(i_hdr, text="Уровень: 5", text_color="#38bdf8", font=("Arial", 13, "bold"))
    app.interp_lbl.pack(side="right")
    app.interp_sl = ctk.CTkSlider(i_box, from_=1, to=10, number_of_steps=9, command=lambda v: app.interp_lbl.configure(text=f"Уровень: {int(v)}"))
    app.interp_sl.set(5)
    app.interp_sl.configure(state="disabled")
    app.interp_sl.pack(fill="x", padx=10, pady=(8, 4))
    ctk.CTkLabel(i_box, text="1 — легкое сглаживание | 10 — плавный Optical Flow", font=("Arial", 11), text_color="#9ca3af").pack(pady=(0, 8))
    s_box = ctk.CTkFrame(right)
    s_box.pack(fill="x", padx=15, pady=10)
    s_hdr = ctk.CTkFrame(s_box, fg_color="transparent")
    s_hdr.pack(fill="x", padx=10, pady=(8, 0))
    app.stab_sw = ctk.CTkSwitch(s_hdr, text="Стабилизация кадров", font=("Arial", 13, "bold"), command=app.toggle_ui)
    app.stab_sw.pack(side="left")
    app.stab_lbl = ctk.CTkLabel(s_hdr, text="Сила: 5", text_color="#a78bfa", font=("Arial", 13, "bold"))
    app.stab_lbl.pack(side="right")
    app.stab_sl = ctk.CTkSlider(s_box, from_=1, to=10, number_of_steps=9, command=lambda v: app.stab_lbl.configure(text=f"Сила: {int(v)}"))
    app.stab_sl.set(5)
    app.stab_sl.configure(state="disabled")
    app.stab_sl.pack(fill="x", padx=10, pady=(8, 4))
    ctk.CTkLabel(s_box, text="Выравнивает горизонт и тряску между кадрами", font=("Arial", 11), text_color="#9ca3af").pack(pady=(0, 8))
    app.btn_render = ctk.CTkButton(right, text="🎬 СОЗДАТЬ ТАЙМЛАПС", height=48, font=("Arial", 15, "bold"), fg_color="#7c3aed", hover_color="#6d28d9", command=app.start_render)
    app.btn_render.pack(fill="x", padx=15, pady=(18, 8))
    app.progress = ctk.CTkProgressBar(right)
    app.progress.set(0)
    app.progress.pack(fill="x", padx=15, pady=5)
    app.status_lbl = ctk.CTkLabel(right, text="Готов к сборке", text_color="#4ade80", wraplength=350)
    app.status_lbl.pack(padx=15, pady=(2, 10))
